// A companion generator that references every declaration emitted by
// skir-rust-gen through its symbol provider. Compiling and testing the e2e
// crate checks that the provider agrees with generateCode.
import { GENERATOR as RUST } from "../dist/index.js";

export const GENERATOR = {
  id: "symbols-check",
  configType: RUST.configType,
  generateCode(input) {
    const symbols = RUST.symbols(input);
    const records = [];
    const methods = [];
    const rebuilds = [];
    for (const module of input.modules) {
      for (const location of module.records) {
        const record = symbols.record(location).reference;
        records.push(`::std::any::type_name::<${record}>(),\n`);
        if (location.record.recordType !== "enum") {
          continue;
        }
        const arms = location.record.fields.map((variant) => {
          const constructor = symbols.variantConstructor(location, variant);
          const value = variant.type
            ? `(${symbols.variantValue(location, variant).reference.replace("{value}", "self")}).clone()`
            : "";
          const rebuilt = constructor.reference.replace("{value}", value);
          return `${symbols.variant(location, variant).reference} => ${rebuilt},\n`;
        });
        rebuilds.push(
          `impl Rebuild for ${record} {\n`,
          "fn rebuild(&self) -> Self {\n",
          "match self {\n",
          ...arms,
          "_ => self.clone(),\n",
          "}\n",
          "}\n",
          "}\n\n",
        );
      }
      for (const method of module.methods) {
        methods.push(`let _ = ${symbols.method(module, method).reference};\n`);
      }
    }
    const code = [
      "// Generated by e2e-test/symbols_check.mjs\n\n",
      "pub fn records() -> ::std::vec::Vec<&'static str> {\n",
      "::std::vec![\n",
      ...records,
      "]\n",
      "}\n\n",
      "pub fn methods() {\n",
      ...methods,
      "}\n\n",
      "/// Rebuilds the variant from its own value, through the symbol provider.\n",
      "pub trait Rebuild {\n",
      "fn rebuild(&self) -> Self;\n",
      "}\n\n",
      ...rebuilds,
    ].join("");
    return { files: [{ path: "mod.rs", code }] };
  },
};
