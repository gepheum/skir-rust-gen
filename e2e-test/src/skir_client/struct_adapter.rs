    fn json_unrecognized_carry_through() {
        let s = make_point_serializer();
        // Dense JSON array with an extra 4th slot (index 3).
        let json = "[0,5,7,42]";
        let p = s.from_json(json, true).unwrap();
        assert_eq!(p.x, 5);
        assert_eq!(p.y, 7);
        assert!(p._unrecognized.is_some());

        // Re-serialize as dense JSON: should include the extra slot.
        let out = s.to_json(&p, false);
        // The output should have 4 elements.
        let arr: serde_json::Value = serde_json::from_str(&out).unwrap();
        assert_eq!(arr.as_array().unwrap().len(), 4);
        assert_eq!(arr[3], serde_json::json!(42));
    }

