    // -------------------------------------------------------------------------
    // A struct with a removed field number
    // -------------------------------------------------------------------------

    #[derive(Clone, Debug, PartialEq, Default)]
    struct Named {
        name: String,
        _unrecognized: Option<Box<UnrecognizedFieldsData<Named>>>,
    }

    fn named_get_unrecognized(t: &Named) -> Option<&UnrecognizedFieldsData<Named>> {
        t._unrecognized.as_deref()
    }
    fn named_set_unrecognized(t: &mut Named, u: Option<Box<UnrecognizedFieldsData<Named>>>) {
        t._unrecognized = u;
    }
    fn named_is_default(t: &Named) -> bool {
        t.name.is_empty() && t._unrecognized.is_none()
    }
    fn named_get_name(t: &Named) -> String {
        t.name.clone()
    }
    fn named_set_name(t: &mut Named, v: String) {
        t.name = v;
    }

    fn make_named_serializer() -> Serializer<Named> {
        let mut a = StructAdapter::new(
            "test",
            "Named",
            "",
            named_get_unrecognized,
            named_set_unrecognized,
        );
        // Field "name" at number 2 (number 1 was removed).
        a.add_removed_number(1);
        a.add_field("name", 2, string_serializer(), "", named_get_name, named_set_name);
        a.finalize();
        crate::skir_client::internal::struct_serializer_from_static(Box::leak(Box::new(a)))
    }

    #[test]
    fn removed_number_slot_skipped_on_decode() {
        let s = make_named_serializer();
        // Binary payload: slots 0,1,2 where slot 1 is the removed field.
        // wire 249 = 3 slots; slot 0: absent (0), slot 1: old removed field "hello" (string),
        // slot 2: name = "Alice"
        // String "hello" encoding: wire 243, length 5, then "hello"
        let mut payload: Vec<u8> = b"skir".to_vec();
        payload.push(249); // 3 slots
        payload.push(0);   // slot 0: absent
        // slot 1: removed field — encode string "hello"
        payload.push(243); // string with length prefix
        payload.push(5);   // length 5
        payload.extend_from_slice(b"hello");
        // slot 2: name = "Alice"
        payload.push(243); // string with length prefix
        payload.push(5);   // length 5
        payload.extend_from_slice(b"Alice");

        let n = s.from_bytes(&payload, false).unwrap();
        assert_eq!(n.name, "Alice");
        assert!(n._unrecognized.is_none());
    }

    #[test]
    fn named_binary_round_trip() {
        let s = make_named_serializer();
        let n = Named { name: "Bob".to_string(), _unrecognized: None };
        let bytes = s.to_bytes(&n);
        let n2 = s.from_bytes(&bytes, false).unwrap();
        assert_eq!(n, n2);
    }
